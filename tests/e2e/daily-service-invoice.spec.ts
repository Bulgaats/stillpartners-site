 await expect(page.getByRole("button",{name:"Add service day"})).toHaveCount(0);
 await page.reload();
 await expect(page.getByText("$1,870.00",{exact:true})).toBeVisible();
 const downloadPromise=page.waitForEvent("download");await page.getByRole("button",{name:"Download PDF",exact:true}).click();
 await (await downloadPromise).saveAs("/tmp/daily-profile-rate.pdf");
