 await page.getByLabel("Rate per tonne (AUD, ex GST)",{exact:true}).fill("600");
 await expect(page.getByText("$2,244.00",{exact:true})).toBeVisible();
 expect(await page.evaluate(()=>JSON.parse(localStorage.getItem("sp-daily-service-invoice:history:v1")!)[0].invoice.lines[0].amount)).toBe("500");
 await second.getByRole("button",{name:"Remove service 2"}).click();
