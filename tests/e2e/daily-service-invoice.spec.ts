 await page.getByLabel("Tonnes",{exact:true}).fill("2.4");
 await expect(page.getByText("$1,320.00",{exact:true})).toBeVisible();
 await page.getByLabel("Next service date (optional)").fill("2026-11-04");
 const second=page.getByRole("article",{name:"Service row 2"});
 await expect(second.getByLabel("Project / site")).toHaveValue("Example site");
 await second.getByLabel("Tonnes",{exact:true}).fill("1");
